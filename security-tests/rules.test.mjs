import { readFileSync } from 'node:fs';
import { test, before, after } from 'node:test';
import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, getDoc, setDoc, updateDoc, deleteDoc, getDocs, collection, query, where, serverTimestamp, Timestamp } from 'firebase/firestore';
let env;
before(async()=>{env=await initializeTestEnvironment({projectId:'demo-planidroid',firestore:{rules:readFileSync(new URL('../firestore.rules',import.meta.url),'utf8')}});await env.withSecurityRulesDisabled(async c=>{for(const uid of ['A','B','C','D'])await setDoc(doc(c.firestore(),'approvedUsers',uid),{enabled:true})})});
after(async()=>{await env?.cleanup()});
const user=(uid)=>env.authenticatedContext(uid,{email:`${uid.toLowerCase()}@example.com`,email_verified:true}).firestore();
test('private: owner only, monotonic version',async()=>{
 const a=user('A'), b=user('B'), u=env.unauthenticatedContext().firestore();
 const data={kind:'TASK',payload:'{}',deleted:false,version:1,updatedAt:serverTimestamp()};
 await assertSucceeds(setDoc(doc(a,'users/A/records/one'),data));await assertFails(getDoc(doc(b,'users/A/records/one')));await assertFails(getDoc(doc(u,'users/A/records/one')));await assertFails(setDoc(doc(b,'users/A/records/two'),data));await assertSucceeds(getDoc(doc(a,'users/A/records/one')));await assertFails(setDoc(doc(a,'users/A/records/one'),{...data,version:3}));await assertSucceeds(setDoc(doc(a,'users/A/records/one'),{...data,version:2}));
});
test('shared: invitation, acceptance, revocation, roles and isolation',async()=>{
 const a=user('A'), b=user('B'), c=user('C'), d=user('D'), anon=env.unauthenticatedContext().firestore();
 const id='space1', sp=x=>doc(x,'sharedSpaces',id), mem=(x,email)=>doc(x,'memberships',`${id}~${email}`);const invitation=(email,role)=>({spaceId:id,email,role,status:'pending',invitedBy:'A',acceptedUid:'',expiresAt:Timestamp.fromMillis(Date.now()+86400000),updatedAt:serverTimestamp()});
 await assertSucceeds(setDoc(sp(a),{ownerUid:'A',kind:'task',title:'Shared',body:'Content',version:1,updatedAt:serverTimestamp()}));
 await assertFails(getDoc(sp(b)));await assertFails(getDoc(sp(anon)));await assertFails(setDoc(mem(b,'b@example.com'),invitation('b@example.com','admin')));
 await assertSucceeds(setDoc(mem(a,'b@example.com'),invitation('b@example.com','reader')));await assertSucceeds(getDocs(query(collection(b,'memberships'),where('email','==','b@example.com'))));await assertFails(getDoc(sp(b)));await assertFails(updateDoc(mem(b,'b@example.com'),{status:'accepted',acceptedUid:'B',role:'admin',updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(mem(b,'b@example.com'),{status:'accepted',acceptedUid:'B',updatedAt:serverTimestamp()}));await assertSucceeds(getDoc(sp(b)));await assertFails(updateDoc(sp(b),{title:'bad',version:2,updatedAt:serverTimestamp()}));await assertFails(getDoc(doc(b,'users/A/records/one')));
 await assertSucceeds(setDoc(mem(a,'c@example.com'),invitation('c@example.com','editor')));await assertSucceeds(updateDoc(mem(c,'c@example.com'),{status:'accepted',acceptedUid:'C',updatedAt:serverTimestamp()}));await assertSucceeds(updateDoc(sp(c),{title:'Edited',version:2,updatedAt:serverTimestamp()}));await assertFails(updateDoc(sp(c),{ownerUid:'C',version:3,updatedAt:serverTimestamp()}));await assertFails(setDoc(mem(c,'d@example.com'),{...invitation('d@example.com','reader'),invitedBy:'C'}));
 await assertSucceeds(setDoc(doc(c,'sharedSpaces',id,'comments','c1'),{authorUid:'C',body:'Comment',createdAt:serverTimestamp()}));await assertFails(setDoc(doc(c,'sharedSpaces',id,'comments','c2'),{authorUid:'A',body:'Spoof',createdAt:serverTimestamp()}));await assertFails(getDoc(sp(d)));await assertSucceeds(deleteDoc(mem(a,'b@example.com')));await assertFails(getDoc(sp(b)));
});

test('house membership inherits furniture access; direct furniture sharing does not expose siblings or house',async()=>{
 const a=user('A'),b=user('B'),c=user('C'),d=user('D');
 const sp=(db,id)=>doc(db,'sharedSpaces',id);
 const mk=(kind,title,parentId='')=>({ownerUid:'A',kind,title,body:'{}',version:1,updatedAt:serverTimestamp(),sourceId:title,parentId,homeName:'Home'});
 const invite=async(id,email,role)=>assertSucceeds(setDoc(doc(a,'memberships',id+'~'+email),{spaceId:id,email,role,status:'pending',invitedBy:'A',acceptedUid:'',expiresAt:Timestamp.fromMillis(Date.now()+86400000),updatedAt:serverTimestamp()}));
 const accept=async(db,id,email,uid)=>assertSucceeds(updateDoc(doc(db,'memberships',id+'~'+email),{status:'accepted',acceptedUid:uid,updatedAt:serverTimestamp()}));
 await assertSucceeds(setDoc(sp(a,'house1'),mk('house','Home')));
 await assertSucceeds(setDoc(sp(a,'fridge1'),mk('furniture','Fridge','house1')));
 await assertSucceeds(setDoc(sp(a,'cabinet1'),mk('furniture','Cabinet','house1')));
 await invite('fridge1','b@example.com','reader');await accept(b,'fridge1','b@example.com','B');
 await assertSucceeds(getDoc(sp(b,'fridge1')));await assertFails(getDoc(sp(b,'cabinet1')));await assertFails(getDoc(sp(b,'house1')));
 await assertFails(getDocs(query(collection(b,'sharedSpaces'),where('ownerUid','==','A'),where('kind','==','furniture'),where('parentId','==','house1'))));
 await invite('house1','c@example.com','editor');await accept(c,'house1','c@example.com','C');
 await assertSucceeds(getDoc(sp(c,'fridge1')));await assertSucceeds(getDoc(sp(c,'cabinet1')));
 await assertSucceeds(getDocs(query(collection(c,'sharedSpaces'),where('ownerUid','==','A'),where('kind','==','furniture'),where('parentId','==','house1'))));
 await assertSucceeds(updateDoc(sp(c,'fridge1'),{body:'{"updated":true}',version:2,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(sp(b,'fridge1'),{body:'{}',version:3,updatedAt:serverTimestamp()}));
 await assertFails(getDoc(sp(d,'fridge1')));
 await assertFails(setDoc(sp(c,'spoof'),{...mk('furniture','Spoof','house1'),ownerUid:'C'}));
 await assertSucceeds(deleteDoc(doc(a,'memberships','house1~c@example.com')));
 await assertFails(getDoc(sp(c,'fridge1')));await assertSucceeds(getDoc(sp(b,'fridge1')));
});

test('approval is manual; unapproved and revoked users cannot read or write application data',async()=>{
 const x=user('X'), a=user('A');
 const payload={kind:'TASK',payload:'{}',deleted:false,version:1,updatedAt:serverTimestamp()};
 await assertSucceeds(getDoc(doc(x,'approvedUsers','X')));
 await assertFails(setDoc(doc(x,'approvedUsers','X'),{enabled:true}));
 await assertFails(getDocs(collection(x,'approvedUsers')));
 await assertFails(getDoc(doc(x,'approvedUsers','A')));
 await assertFails(setDoc(doc(x,'users/X/records/test'),payload));
 await assertFails(getDocs(collection(x,'users/X/records')));
 await assertFails(getDocs(query(collection(x,'sharedSpaces'),where('ownerUid','==','X'))));
 await assertFails(getDocs(query(collection(x,'memberships'),where('email','==','x@example.com'))));
 await env.withSecurityRulesDisabled(async c=>setDoc(doc(c.firestore(),'approvedUsers','X'),{enabled:true}));
 await assertSucceeds(setDoc(doc(x,'users/X/records/test'),payload));
 await assertFails(getDoc(doc(x,'users/A/records/one')));
 await env.withSecurityRulesDisabled(async c=>updateDoc(doc(c.firestore(),'approvedUsers','X'),{enabled:false}));
 await assertFails(getDoc(doc(x,'users/X/records/test')));
 await assertFails(updateDoc(doc(x,'users/X/records/test'),{...payload,version:2}));
 await assertFails(getDoc(doc(x,'sharedSpaces','space1')));
 await assertFails(setDoc(doc(a,'approvedUsers','X'),{enabled:true}));
});

test('Google user can register only own pending request, never overwrite or approve',async()=>{
 const pending=env.authenticatedContext('P',{email:'p@example.com',email_verified:true,firebase:{sign_in_provider:'google.com'}}).firestore();
 const anon=env.unauthenticatedContext().firestore();
 const path=db=>doc(db,'approvedUsers','P');
 const data={enabled:false,email:'p@example.com',createdAt:serverTimestamp()};
 await assertFails(setDoc(path(anon),data));
 await assertFails(setDoc(doc(pending,'approvedUsers','OTHER'),data));
 await assertFails(setDoc(path(pending),{...data,enabled:true}));
 await assertFails(setDoc(path(pending),{...data,email:'other@example.com'}));
 await assertFails(setDoc(path(pending),{...data,admin:true}));
 await assertSucceeds(setDoc(path(pending),data));
 await assertSucceeds(getDoc(path(pending)));
 await assertFails(setDoc(path(pending),data));
 await assertFails(updateDoc(path(pending),{enabled:true}));
 await assertFails(deleteDoc(path(pending)));
 await assertFails(getDocs(collection(pending,'users/P/records')));
 await env.withSecurityRulesDisabled(async c=>updateDoc(path(c.firestore()),{enabled:true}));
 await assertSucceeds(getDocs(collection(pending,'users/P/records')));
 await assertFails(setDoc(path(pending),data));
 await env.withSecurityRulesDisabled(async c=>updateDoc(path(c.firestore()),{enabled:false}));
 await assertFails(getDocs(collection(pending,'users/P/records')));
 await assertFails(updateDoc(path(pending),{enabled:true}));
});
